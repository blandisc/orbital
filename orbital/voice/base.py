"""Lo que comparten las piezas de VoiceController (aquí solo se declara, con su tipo, para que cada pieza lo vea).

Dueño del estado: VoiceController.__init__ (voice/__init__.py) lo arma una sola vez. No hay candados: cada comando se
atiende en el hilo de quien lo pidió (la ruta de Alexa, el iPhone o la tele) y solo toca el catálogo.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from ..catalog import Catalog
    from .parsing import VoiceResult


class _Base:
    catalog: Catalog
    kiosk: Any  # KioskWindow, o None si la interfaz no la abrió Orbital
    tv: Any  # roku.RokuTv
    _candidates: list[dict]  # lo que encontró la última búsqueda de un título (para «otro»)
    _last: dict | None  # lo último que se puso por nombre

    if TYPE_CHECKING:  # viven en la fachada (voice/__init__.py) o en una pieza de más adelante
        def handle_text(self, text: str) -> VoiceResult: ...
        def handle_intent(self, intent: str, slots: dict[str, str] | None = None) -> VoiceResult: ...
        def moment(self) -> str: ...
        def _tips_on(self) -> bool: ...
        def _playing_event(self, message: str, moment: str) -> dict: ...
        def _wake_tv(self) -> None: ...
        # media.py
        def _search_media_intent(self, slots: dict) -> VoiceResult: ...
        @staticmethod
        def _media_options(name: str, slots: dict) -> tuple[str, dict]: ...
        def _vague(self, name: str) -> VoiceResult | None: ...
        def _show_view(self, view: dict, message: str = "") -> dict: ...
        def _watch_exact(self, query: str, kind: str | None = None, options: dict | None = None,
                         ask: bool = False) -> VoiceResult | None: ...
        def _watch_item(self, item, options: dict | None = None) -> VoiceResult: ...
        # controls.py
        def _resume_intent(self, slots: dict) -> VoiceResult: ...
        def _watch_episode_intent(self, slots: dict) -> VoiceResult: ...
